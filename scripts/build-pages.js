/* Build the static Cloudflare Pages output.
 *
 * Usage:
 *   BGR_MODEL_URL="https://<model-host>/<versioned-key>/model_fp16.onnx" npm run build:pages
 *
 * The ONNX model itself is never copied into `dist`. It must be published on
 * an approved static host such as Cloudflare R2. The model URL is injected
 * into the generated `js/background-remover/model-config.mjs` module.
 *
 * For local cross-origin testing only, an http://localhost URL is accepted
 * when ALLOW_INSECURE_MODEL_URL=1.
 */
'use strict';

const fs = require('fs');
const path = require('path');
const { pathToFileURL } = require('url');

const ROOT = path.resolve(__dirname, '..');
const OUT = path.join(ROOT, 'dist');
const LIMIT = 25 * 1024 * 1024;
const MODEL_REL = 'vendor/background-removal/model_fp16.onnx';
const CONFIG_REL = 'js/background-remover/model-config.mjs';

const SKIP_TOP_LEVEL = new Set([
  '.git',
  '.github',
  '.wrangler',
  'dist',
  'docs',
  'functions',
  'node_modules',
  'playwright-report',
  'scripts',
  'test-results',
  'tests',
  'workers'
]);

const SKIP_FILES = new Set([
  '.env',
  '.gitignore',
  'package-lock.json',
  'package.json',
  'playwright.config.js',
  'vitest.config.js',
  'wrangler.toml',
  'wrangler.jsonc',
  'wrangler.json'
]);

function fail(message) {
  console.error('\nCloudflare Pages build failed:\n' + message + '\n');
  process.exit(1);
}

function isSkipped(relativePath) {
  const normalized = relativePath.split(path.sep).join('/');
  const top = normalized.split('/')[0];
  if (SKIP_TOP_LEVEL.has(top)) return true;
  if (SKIP_FILES.has(normalized)) return true;
  if (/^\.env(\.|$)/.test(normalized)) return true;
  if (normalized === MODEL_REL) return true;
  return false;
}

function copyTree(from, to, relative = '') {
  for (const entry of fs.readdirSync(from, { withFileTypes: true })) {
    const rel = relative ? path.join(relative, entry.name) : entry.name;
    if (isSkipped(rel)) continue;
    const source = path.join(from, entry.name);
    const target = path.join(to, entry.name);
    if (entry.isDirectory()) {
      fs.mkdirSync(target, { recursive: true });
      copyTree(source, target, rel);
      continue;
    }
    if (!entry.isFile()) continue;
    const size = fs.statSync(source).size;
    if (size > LIMIT) {
      fail(
        rel +
          ' is ' +
          (size / 1024 / 1024).toFixed(2) +
          ' MiB, which exceeds the 25 MiB Cloudflare Pages file limit. ' +
          'Host large assets outside Pages.'
      );
    }
    fs.mkdirSync(path.dirname(target), { recursive: true });
    fs.copyFileSync(source, target);
  }
}

function validateModelUrl(value) {
  if (!value) {
    fail(
      'BGR_MODEL_URL is not set. Set it to the public, versioned URL of ' +
        'model_fp16.onnx in the Cloudflare Pages production environment.'
    );
  }
  let url;
  try {
    url = new URL(value);
  } catch (error) {
    fail('BGR_MODEL_URL is not a valid absolute URL: ' + value);
  }
  if (url.username || url.password) {
    fail('BGR_MODEL_URL must not contain credentials. Use a public, read-only model URL.');
  }
  const allowInsecure = process.env.ALLOW_INSECURE_MODEL_URL === '1';
  const local = /^(localhost|127\.0\.0\.1|\[::1\])$/.test(url.hostname);
  if (url.protocol !== 'https:' && !(allowInsecure && local && url.protocol === 'http:')) {
    fail('BGR_MODEL_URL must use https:// (http:// is only allowed for localhost tests).');
  }
  if (!url.pathname.toLowerCase().endsWith('.onnx')) {
    fail('BGR_MODEL_URL must point directly at the .onnx model file.');
  }
  return url;
}

async function main() {
  const modelUrl = validateModelUrl(process.env.BGR_MODEL_URL);
  const sourceConfigUrl = pathToFileURL(path.join(ROOT, CONFIG_REL)).href;
  const { MODEL_CONFIG } = await import(sourceConfigUrl + '?build=' + Date.now());

  fs.rmSync(OUT, { recursive: true, force: true });
  fs.mkdirSync(OUT, { recursive: true });
  copyTree(ROOT, OUT);

  if (fs.existsSync(path.join(OUT, MODEL_REL))) {
    fail('The ONNX model was copied into dist. It must stay outside the Pages output.');
  }

  const generated = Object.assign({}, MODEL_CONFIG, { url: modelUrl.href });
  fs.writeFileSync(
    path.join(OUT, CONFIG_REL),
    '/* Generated by scripts/build-pages.js — do not edit the dist copy. */\n' +
      'export const MODEL_CONFIG = Object.freeze(' +
      JSON.stringify(generated, null, 2) +
      ');\n'
  );

  let files = 0;
  let bytes = 0;
  let largest = { path: '', size: 0 };
  const walk = (directory, relative = '') => {
    for (const entry of fs.readdirSync(directory, { withFileTypes: true })) {
      const rel = relative ? path.join(relative, entry.name) : entry.name;
      const full = path.join(directory, entry.name);
      if (entry.isDirectory()) {
        walk(full, rel);
        continue;
      }
      if (!entry.isFile()) continue;
      const size = fs.statSync(full).size;
      files += 1;
      bytes += size;
      if (size > largest.size) largest = { path: rel, size };
      if (size > LIMIT) {
        fail(rel + ' is ' + (size / 1024 / 1024).toFixed(2) + ' MiB, over the 25 MiB limit.');
      }
    }
  };
  walk(OUT);

  console.log('Cloudflare Pages output: ' + OUT);
  console.log('Files: ' + files + ' (' + (bytes / 1024 / 1024).toFixed(2) + ' MiB total)');
  console.log(
    'Largest file: ' +
      largest.path.split(path.sep).join('/') +
      ' (' +
      (largest.size / 1024 / 1024).toFixed(2) +
      ' MiB)'
  );
  console.log('Model URL: ' + modelUrl.href);
  console.log('Model excluded from Pages: ' + MODEL_REL);
  if (!modelUrl.href.includes('962e679') && !modelUrl.href.includes(MODEL_CONFIG.sha256.slice(0, 12))) {
    console.warn(
      'Warning: use a versioned object key (revision or hash) and long-lived immutable caching.'
    );
  }
}

main().catch((error) => fail(error && error.stack ? error.stack : String(error)));
